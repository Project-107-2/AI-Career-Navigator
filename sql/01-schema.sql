CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS role_skills (
    role_id INTEGER NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    required_level INTEGER NOT NULL CHECK (required_level BETWEEN 1 AND 5),
    PRIMARY KEY (role_id, skill_id)
);

CREATE TABLE IF NOT EXISTS vacancies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id INTEGER REFERENCES roles(id) ON DELETE SET NULL,
    external_id VARCHAR(120) NOT NULL,
    source VARCHAR(40) NOT NULL DEFAULT 'hh.ru',
    title VARCHAR(250) NOT NULL,
    employer VARCHAR(250),
    salary_from NUMERIC(12, 2),
    salary_to NUMERIC(12, 2),
    published_at TIMESTAMPTZ,
    UNIQUE (source, external_id),
    CHECK (salary_from IS NULL OR salary_from >= 0),
    CHECK (salary_to IS NULL OR salary_to >= 0)
);

CREATE TABLE IF NOT EXISTS vacancy_skills (
    vacancy_id INTEGER NOT NULL REFERENCES vacancies(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    PRIMARY KEY (vacancy_id, skill_id)
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    grade VARCHAR(50) NOT NULL DEFAULT '',
    target_role_id INTEGER REFERENCES roles(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS user_skill_assessments (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    level INTEGER NOT NULL CHECK (level BETWEEN 1 AND 5),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, skill_id)
);

CREATE TABLE IF NOT EXISTS skill_test_results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills(id),
    score INTEGER NOT NULL CHECK (score BETWEEN 0 AND 100),
    confirmed_level INTEGER CHECK (confirmed_level BETWEEN 1 AND 5),
    passed BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS skill_dependencies (
    skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    prerequisite_skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    PRIMARY KEY (skill_id, prerequisite_skill_id),
    CHECK (skill_id <> prerequisite_skill_id)
);

CREATE TABLE IF NOT EXISTS skill_synonyms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    synonym VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS skill_materials (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id INTEGER NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    title VARCHAR(250) NOT NULL,
    url TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_vacancies_role ON vacancies(role_id);
CREATE INDEX IF NOT EXISTS idx_assessments_user ON user_skill_assessments(user_id);
CREATE INDEX IF NOT EXISTS idx_vacancy_skills_skill ON vacancy_skills(skill_id);
